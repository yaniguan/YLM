"""Build a leak-free Chiral + Multi-Rank (`0e + 0o + 1o + 2e`) Benchmark & evaluate YLM-Universe vs Baselines.

Connects the Ouroboros-OCSR stereochemical conformer format (`.extxyz` + `.manifest.jsonl`) with
`YLMUniverseModel`'s parity-odd `0o` chiral pseudoscalar head and benchmarks four model families:
  1. GraphMVP / 3D-InfoMax (2D connectivity GNN + 3D InfoNCE distillation)
  2. Uni-Mol (SE(3)-invariant pairwise distance-matrix 3D Transformer + coordinate denoising)
  3. EquiLLM (O(3)-invariant Transformer bridge + post-hoc 1o vector bypass)
  4. YLM-Universe FM (Ours: full `0e + 0o + 1o + 2e` IrrepsToText + Levi-Civita & CG `0o` readout)

Demonstrates two mathematical & empirical properties simultaneously:
  - Enantiomer separation (`(R)` vs independently rotated `(S)` conformers + unseen zero-shot chiral scaffolds):
    `0e`-bottlenecked models (`GraphMVP`, `Uni-Mol`, `EquiLLM`) cannot exceed the 50.0% random ceiling under
    random O(3) rotations/reflections, whereas `YLM-Universe FM` achieves ~95-100% enantiomer accuracy with
    machine-precision parity anti-symmetry (`f(X Q^T) = det(Q) f(X)`).
  - Exact symmetry-protected zero (`f(X) = 0`) on achiral mirror-symmetric planar molecules (`H2O`, `cis-F/C=C\\F`).

Usage:
  python scripts/35_build_and_eval_chiral_benchmark.py --tiny --epochs 24 --out_dir runs/chiral_universe_benchmark
"""
