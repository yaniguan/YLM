"""Tables for TensorQA-v1 from runs_hoffman2/v1_*/{results.json,records.npz}  ->  results_v1.md

Uncertainty: per-question metrics are averaged over seeds, then molecules are resampled (paired bootstrap, 2000 draws);
intervals are 95% over molecules. A seed-to-seed std is shown next to it. The same question/molecule sets are used for
every model, so differences are paired.

  python scripts/27_analyze_v1.py [--runs runs_hoffman2] [--out results_v1.md]
"""
import argparse
import glob
import json
import os
from collections import defaultdict

import numpy as np

SPLITS = ["test", "test_heldout", "scaf", "scaf_heldout", "comb"]
TASKS = ["force", "diff", "proj"]
MODELS = [("bc", "B/C-lite (text -> coefficients)"), ("optA", "Option A (one pointer)"),
          ("prog", "learned parser + exact executor"), ("rule", "rule parser + exact executor"),
          ("oracle", "true program + exact executor (diagnostic)")]
VARIANTS = [("bcso3", "B/C-lite, parity=so3 (0o sign kept)"), ("prognosup", "learned parser, no program supervision"),
            ("progaux", "learned parser + force supervision"), ("ruleaux", "rule parser + force supervision"),
            ("oracleaux", "true program + force supervision")]


def load(runs, prefix):
    res, rec = [], []
    for d in sorted(glob.glob(f"{runs}/v1_{prefix}_s[0-9]")):
        if os.path.exists(f"{d}/results.json"):
            res.append(json.load(open(f"{d}/results.json")))
            if os.path.exists(f"{d}/records.npz"):
                rec.append(np.load(f"{d}/records.npz"))
    return res, rec


def mean_std(res, getter):
    v = []
    for r in res:
        try:
            x = getter(r)
        except (KeyError, TypeError):
            continue
        if x is not None:
            v.append(x)
    return (float(np.mean(v)), float(np.std(v)), len(v)) if v else (None, None, 0)


def fmt(ms, nd=3):
    m, s, n = ms
    return "n/a" if m is None else f"{m:.{nd}f} ± {s:.{nd}f}" if n > 1 else f"{m:.{nd}f}"


def boot_ci(per_row, mol, draws=2000, seed=0):
    """95% CI of the mean over rows, resampling molecules"""
    ids, inv = np.unique(mol, return_inverse=True)
    s = np.bincount(inv, weights=per_row)
    c = np.bincount(inv)
    rng = np.random.RandomState(seed)
    idx = rng.randint(0, len(ids), (draws, len(ids)))
    means = s[idx].sum(1) / c[idx].sum(1)
    return np.percentile(means, [2.5, 97.5])


def pooled(rec, key):
    return np.mean([r[key] for r in rec], axis=0) if rec else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", default="runs_hoffman2")
    ap.add_argument("--data", default="data/tensorqa_v1.json")
    ap.add_argument("--out", default="results_v1.md")
    args = ap.parse_args()
    qs = json.load(open(args.data)) if os.path.exists(args.data) else None
    L = ["# TensorQA-v1 results (generated by scripts/27_analyze_v1.py)", "",
         "Cosine between predicted and true vector (higher is better) and MAE in hartree/bohr. Mean ± std over seeds; "
         "`[lo, hi]` is the 95% molecule-level bootstrap interval of the seed-averaged per-question metric.", ""]
    runs = {k: load(args.runs, k) for k, _ in MODELS + VARIANTS}

    for metric, title in (("cosine", "Cosine"), ("mae", "MAE")):
        L += [f"## {title} by split and task", ""]
        for sp in SPLITS:
            L += [f"### split `{sp}`", "", "| model | " + " | ".join(TASKS) + " |", "|---|" + "---|" * len(TASKS)]
            for k, name in MODELS + VARIANTS:
                res, rec = runs[k]
                if not res:
                    continue
                cells = []
                for t in TASKS:
                    ms = mean_std(res, lambda r: r[sp][t][metric])
                    cell = fmt(ms, 3 if metric == "cosine" else 4)
                    if ms[0] is not None and rec and qs is not None and metric == "cosine":
                        try:
                            rows = rec[0][f"{sp}/row"]
                            sel = np.array([qs[i]["task"] == t for i in rows])
                            lo, hi = boot_ci(pooled(rec, f"{sp}/cos")[sel], rec[0][f"{sp}/mol"][sel])
                            cell += f" [{lo:.2f}, {hi:.2f}]"
                        except KeyError:
                            pass
                    cells.append(cell)
                L.append(f"| {name} | " + " | ".join(cells) + " |")
            L.append("")

    L += ["## 2x2 diagnosis (split `test`, cosine)", "",
          "| physical quantity | program | force | diff | proj | source |", "|---|---|---|---|---|---|"]
    L.append("| true | true | 1.000 | 1.000 | 1.000 | executor check (all models, by construction) |")
    for k, label in (("rule", "rule parser"), ("prog", "learned parser"), ("ruleaux", "rule parser (aux)"), ("progaux", "learned parser (aux)")):
        res = runs[k][0]
        if res:
            L.append("| true | " + label + " | " + " | ".join(fmt(mean_std(res, lambda r, t=t: r["test"][t]["true_forces_cosine"])) for t in TASKS) + " | 'true_forces' |")
    for k, label in (("oracle", "true"), ("oracleaux", "true (aux)")):
        res = runs[k][0]
        if res:
            L.append("| predicted | " + label + " | " + " | ".join(fmt(mean_std(res, lambda r, t=t: r["test"][t]["cosine"])) for t in TASKS) + " | oracle |")
    for k, label in (("rule", "rule parser"), ("prog", "learned parser"), ("ruleaux", "rule parser (aux)"), ("progaux", "learned parser (aux)")):
        res = runs[k][0]
        if res:
            L.append("| predicted | " + label + " | " + " | ".join(fmt(mean_std(res, lambda r, t=t: r["test"][t]["cosine"])) for t in TASKS) + " | end to end |")
    L.append("")

    L += ["## Program accuracy (exact = task and both atoms right)", "", "| model | split | task acc | atom A acc | atom B acc | exact |", "|---|---|---|---|---|---|"]
    for k in ("rule", "prog", "progaux", "prognosup"):
        res = runs[k][0]
        for sp in SPLITS:
            if res and sp in res[0] and "program" in res[0][sp]:
                g = lambda f, r, sp=sp: r[sp]["program"][f]   # noqa: E731
                L.append(f"| {k} | {sp} | " + " | ".join(fmt(mean_std(res, lambda r, f=f: g(f, r))) for f in ("task_acc", "atom_a_acc", "atom_b_acc", "exact")) + " |")
    L.append("")

    L += ["## Held-out wording families (split `test_heldout`, cosine by style)", ""]
    for k, name in MODELS:
        res = runs[k][0]
        if res and "by_style" in res[0].get("test_heldout", {}):
            styles = sorted(res[0]["test_heldout"]["by_style"])
            L += [f"**{name}**: " + ", ".join(f"{s} {fmt(mean_std(res, lambda r, s=s: r['test_heldout']['by_style'][s]['cosine']), 2)}" for s in styles), ""]

    L += ["## Symmetry (relative error of the answer under random proper rotations / reflections, split `test`)", "",
          "| model | rotation | reflection |", "|---|---|---|"]
    for k, name in MODELS + VARIANTS:
        res = runs[k][0]
        if res:
            L.append(f"| {name} | {fmt(mean_std(res, lambda r: r['test']['eq_err_rotation']), 6)} | {fmt(mean_std(res, lambda r: r['test']['eq_err_reflection']), 6)} |")
    L.append("")

    L += ["## Counterfactual identities (relative violation, lower is better; `labels` is the label noise floor)", "",
          "| model | swap D(A,B)+D(B,A) | chain D(A,C)-D(A,B)-D(B,C) |", "|---|---|---|"]
    for k, name in MODELS:
        res = runs[k][0]
        if res and "consistency" in res[0].get("cf", {}):
            L.append(f"| {name} | {fmt(mean_std(res, lambda r: r['cf']['consistency']['swap_model']))} | {fmt(mean_std(res, lambda r: r['cf']['consistency']['chain_model']))} |")
    for k, _ in MODELS:
        res = runs[k][0]
        if res and "consistency" in res[0].get("cf", {}):
            c = res[0]["cf"]["consistency"]
            L.append(f"| labels | {c['swap_labels']:.4f} | {c['chain_labels']:.4f} |")
            break
    L.append("")
    open(args.out, "w").write("\n".join(L))
    print("wrote", args.out, "| models with results:", {k: len(v[0]) for k, v in runs.items() if v[0]})


if __name__ == "__main__":
    main()
